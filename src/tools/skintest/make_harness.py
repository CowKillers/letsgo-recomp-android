"""make_harness.py <vertex shader .glsl> [out.cpp]: a C++ program that runs a translated vertex shader on the CPU.

The renderer's GLSL (LARECOMP_SAVE_MSL=1 -> build/glsl/<addr>_vs.glsl) is a scalar state machine (switch on pc) over
uint / float registers: with a few GLSL look-alikes it compiles as C++. The program reads the inputs of one skinned
draw dumped by the renderer (LARECOMP_DUMP_SKIN* -> build/skin/: info.txt, verts.bin, cbN.bin) and, for each vertex,
runs the shader twice - with the real bone weights and with 100% on the first bone - and prints both positions.

  real ~ one-bone (small weights barely move a vertex): the translated shader blends bones correctly on the CPU, so
                                                        a wrong picture comes from what the GPU is fed.
  real far off one-bone:                                the translation of the blend is wrong.

The generated .cpp contains the game's (translated) shader code: it stays local (build/, never committed).
"""
import os
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join('build', 'skintest.cpp')
body = src[src.index('void main() {'):].replace('void main() {', 'static void shader_main() {', 1)
ins = re.findall(r'layout\(location = (\d+)\) in (u?vec4) a\d+;', src)
cbs = re.findall(r'uniform CB(\d+) \{ uvec4 cb\d+\[(\d+)\]; \};', src)
outs = re.findall(r'layout\(location = (\d+)\) out vec4 (v\d+);', src)

prelude = r'''// Generated by tools/skintest/make_harness.py - contains a translated game shader: never commit.
#include <cstdint>
#include <cmath>
#include <cstring>
#include <cstdio>
#include <cstdlib>
#include <algorithm>
typedef uint32_t uint;
struct vec4 { float x, y, z, w; vec4(float a = 0, float b = 0, float c = 0, float d = 0) : x(a), y(b), z(c), w(d) {}
  float &operator[](int i) { return (&x)[i]; } float operator[](int i) const { return (&x)[i]; } };
struct uvec4 { uint x, y, z, w; uint &operator[](int i) { return (&x)[i]; } uint operator[](int i) const { return (&x)[i]; } };
static inline uint as_u(float f) { uint u; memcpy(&u, &f, 4); return u; }
static inline uint as_u(uint u) { return u; }
static inline uint as_u(int i) { return (uint)i; }
static inline float as_f(uint u) { float f; memcpy(&f, &u, 4); return f; }
static inline float as_f(float f) { return f; }
static inline float as_f(int i) { return as_f((uint)i); }
static inline float fma(float a, float b, float c) { return std::fmaf(a, b, c); }
static inline float inversesqrt(float x) { return 1.0f / std::sqrt(x); }
#define cbr(cb, off) cb[std::min((uint)((off) >> 4), (uint)(sizeof(cb) / sizeof(cb[0]) - 1))][((off) >> 2) & 3u]
static vec4 gl_Position;
'''
decl = ''.join(f'static {t} a{n};\n' for n, t in ins)
decl += ''.join(f'static uvec4 cb{n}[{m}];\n' for n, m in cbs)
decl += ''.join(f'static vec4 {v};\n' for _, v in outs)
has12 = any(n == '12' for n, _ in ins)
one_bone = '#define a12 (g_one_bone ? vec4(1, 0, 0, 0) : a12_real)\n' if has12 else ''
if has12:
    decl = decl.replace('static vec4 a12;', 'static vec4 a12_real;')
decl += 'static bool g_one_bone;\n' + one_bone

loaders = '\n'.join(f'    if (a == {n}) load_attr(p + off, fmt, &a{n}{"_real" if n == "12" else ""});' for n, _ in ins)
cbload = '\n'.join(f'    snprintf(path, sizeof path, "%s/cb{n}.bin", dir); load(path, cb{n}, sizeof cb{n});' for n, _ in cbs)
main = r'''
static float h2f(uint16_t h) { uint s = (h & 0x8000u) << 16, e = (h >> 10) & 0x1F, m = h & 0x3FF;
  if (e == 0) return (s ? -1.0f : 1.0f) * m * 5.9604644775390625e-8f;
  if (e == 31) return as_f(s | 0x7F800000u | (m << 13));
  return as_f(s | ((e + 112) << 23) | (m << 13)); }
static size_t load(const char *p, void *dst, size_t cap) { FILE *f = fopen(p, "rb"); if (!f) return 0; size_t n = fread(dst, 1, cap, f); fclose(f); return n; }
// NVN vertex formats seen in the game (runtime/nvn/vulkan/exec.c vertex_format)
static void load_attr(const uint8_t *p, unsigned fmt, vec4 *o) {
  float f[4] = {0, 0, 0, 1}; uint16_t h[4];
  switch (fmt) {
  case 0x16: memcpy(f, p, 8); break;                                   // RG32F
  case 0x22: memcpy(f, p, 12); break;                                  // RGB32F
  case 0x2e: memcpy(f, p, 16); break;                                  // RGBA32F
  case 0x11: memcpy(h, p, 4); f[0] = h2f(h[0]); f[1] = h2f(h[1]); break;  // RG16F
  case 0x29: memcpy(h, p, 8); for (int i = 0; i < 4; i++) f[i] = h2f(h[i]); break;  // RGBA16F
  case 0x25: for (int i = 0; i < 4; i++) f[i] = p[i] / 255.0f; break;  // RGBA8 UNORM
  default: fprintf(stderr, "format %#x as float vec4: unknown\n", fmt);
  }
  *o = vec4(f[0], f[1], f[2], f[3]);
}
static void load_attr(const uint8_t *p, unsigned fmt, uvec4 *o) {
  uint u[4] = {0, 0, 0, 1};
  switch (fmt) {
  case 0x27: for (int i = 0; i < 4; i++) u[i] = p[i]; break;          // RGBA8 UINT
  case 0x2c: { uint16_t s[4]; memcpy(s, p, 8); for (int i = 0; i < 4; i++) u[i] = s[i]; } break;  // RGBA16 UINT
  case 0x2f: memcpy(u, p, 16); break;                                  // RGBA32 UINT
  default: fprintf(stderr, "format %#x as uint vec4: unknown\n", fmt);
  }
  *o = {u[0], u[1], u[2], u[3]};
}
int main(int argc, char **argv) {
  const char *dir = argc > 1 ? argv[1] : "build/skin";
  char path[512], line[256];
  static uint8_t vb[1 << 20];
  struct { int a; unsigned fmt, off; } at[32]; int nat = 0; unsigned stride = 0;
  snprintf(path, sizeof path, "%s/info.txt", dir);
  FILE *fi = fopen(path, "r"); if (!fi) { printf("no %s\n", path); return 1; }
  while (fgets(line, sizeof line, fi)) {
    unsigned long long vs; int a; unsigned fmt, off;
    if (sscanf(line, "vs %llx stride %u", &vs, &stride) == 2) continue;
    if (sscanf(line, "attr %d fmt %x off %u", &a, &fmt, &off) == 3 && nat < 32) at[nat++] = {a, fmt, off};
  }
  fclose(fi);
''' + cbload + r'''
  snprintf(path, sizeof path, "%s/verts.bin", dir); size_t nb = load(path, vb, sizeof vb);
  static float gpu[1 << 18][4];  // (tools/rdc_draw.py: the GPU's gl_Position per vertex, from a RenderDoc capture)
  snprintf(path, sizeof path, "%s/gpu_pos.bin", dir); size_t ng = load(path, gpu, sizeof gpu) / 16;
  int nv = stride ? (int)(nb / stride) : 0;
  printf("stride %u, %d vertices\n", stride, nv);
  double worst = 0;
  for (int i = 0; i < nv; i++) {
    const uint8_t *p = vb + (size_t)i * stride;
    for (int k = 0; k < nat; k++) {
      int a = at[k].a; unsigned fmt = at[k].fmt, off = at[k].off;
''' + loaders + r'''
    }
    g_one_bone = false; shader_main(); vec4 real = gl_Position;
    g_one_bone = true;  shader_main(); vec4 one = gl_Position;
    double d = 0; for (int c = 0; c < 4; c++) d = std::max(d, (double)std::fabs(real[c] - one[c]));
    worst = std::max(worst, d);
    double dg = 0;
    if ((size_t)i < ng) for (int c = 0; c < 4; c++) dg = std::max(dg, (double)std::fabs(real[c] - gpu[i][c]));
    if (i < 24 || d > 1.0 || dg > 1.0) {
      printf("v%-3d bones %u %u %u %u w %.2f %.2f %.2f %.2f | real %9.3f %9.3f %9.3f %9.3f | one-bone %9.3f %9.3f %9.3f %9.3f | diff %.3f",
             i, a11[0], a11[1], a11[2], a11[3], a12_real[0], a12_real[1], a12_real[2], a12_real[3],
             real.x, real.y, real.z, real.w, one.x, one.y, one.z, one.w, d);
      if ((size_t)i < ng) printf(" | gpu %9.3f %9.3f %9.3f %9.3f", gpu[i][0], gpu[i][1], gpu[i][2], gpu[i][3]);
      printf("\n");
    }
  }
  printf("largest |real - one-bone| over all vertices: %.3f\n", worst);
}
'''
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write(prelude + decl + body + main)
print(out)
